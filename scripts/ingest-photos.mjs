#!/usr/bin/env node
/**
 * Ingest the studio's real photographs.
 *
 *   npm run photos
 *
 * Scans incoming/ for camera files, writes responsive WebP derivatives into
 * public/media/photos/, and emits src/lib/media/catalogue.json describing what
 * was found — dimensions, orientation and a stable id per frame.
 *
 * Sized on the WIDTH axis deliberately. These are mostly portrait frames
 * (3375x4219, 5304x7952), and the site lays them out in columns, so the width a
 * photo is displayed at is what decides how much detail it needs. Picking sizes
 * off the long edge would ship enormous files to show a 600px-wide column.
 */

import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const IN = path.join(ROOT, "incoming");
const OUT = path.join(ROOT, "public/media/photos");
const CATALOGUE = path.join(ROOT, "src/lib/media/catalogue.json");

const WIDTHS = [480, 800, 1200, 1600];
const QUALITY = { 480: 72, 800: 78, 1200: 82, 1600: 84 };

const SOURCE_RE = /\.(jpe?g|png|webp|avif)$/i;

/** A stable, URL-safe id from a camera filename. */
function toId(file) {
  return file
    .replace(SOURCE_RE, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

async function main() {
  await fs.mkdir(OUT, { recursive: true });

  const files = (await fs.readdir(IN))
    .filter((f) => SOURCE_RE.test(f))
    .sort();

  if (!files.length) {
    console.error(`No photographs found in incoming/.`);
    process.exit(1);
  }

  const only = process.argv.slice(2);

  /*
   * Processing a subset used to rewrite the catalogue from just that subset,
   * silently dropping every other photograph from the site. Existing entries
   * are carried over and the processed ones replace their old records.
   */
  let existing = [];
  if (only.length) {
    try {
      const prev = JSON.parse(await fs.readFile(CATALOGUE, "utf8"));
      existing = Array.isArray(prev.photos) ? prev.photos : [];
    } catch {
      console.warn("  ! no readable catalogue to merge into — writing fresh");
    }
  }

  const catalogue = [];
  let built = 0;
  let bytes = 0;
  const seen = new Set();

  for (const file of files) {
    let id = toId(file);
    // camera folders routinely contain "001.jpg" and "001 (2).jpg"
    let n = 2;
    while (seen.has(id)) id = `${toId(file)}-${n++}`;
    seen.add(id);

    if (only.length && !only.includes(id)) continue;

    const src = path.join(IN, file);
    const meta = await sharp(src).metadata();
    const w = meta.width ?? 0;
    const h = meta.height ?? 0;
    if (!w || !h) {
      console.error(`  ✗  ${file} — unreadable`);
      continue;
    }

    const ratio = w / h;
    const orientation =
      ratio > 1.15 ? "landscape" : ratio < 0.87 ? "portrait" : "square";

    const widths = [];
    for (const target of WIDTHS) {
      if (w < target * 0.75) continue; // never upscale
      const info = await sharp(src)
        .rotate() // honour EXIF orientation
        .resize({ width: target, withoutEnlargement: true })
        .webp({ quality: QUALITY[target], effort: 5 })
        .toFile(path.join(OUT, `${id}-${target}.webp`));
      widths.push(target);
      bytes += info.size;
    }

    const thumb = await sharp(src)
      .rotate()
      .resize({ width: 24 })
      .blur(1.5)
      .webp({ quality: 40 })
      .toFile(path.join(OUT, `${id}-thumb.webp`));
    bytes += thumb.size;

    catalogue.push({
      id,
      file,
      width: w,
      height: h,
      ratio: +ratio.toFixed(3),
      orientation,
      widths,
    });

    built += 1;
    process.stdout.write(
      `  ✓  ${id.padEnd(26)} ${String(w).padStart(5)}x${String(h).padEnd(5)} ${orientation}\n`,
    );
  }

  if (only.length && existing.length) {
    const done = new Set(catalogue.map((p) => p.id));
    for (const prev of existing) if (!done.has(prev.id)) catalogue.push(prev);
  }

  catalogue.sort((a, b) => a.id.localeCompare(b.id));

  await fs.writeFile(
    CATALOGUE,
    `${JSON.stringify(
      {
        $comment:
          "Generated by scripts/ingest-photos.mjs — do not edit by hand. Run `npm run photos` after adding files to incoming/.",
        generatedAt: new Date().toISOString(),
        count: catalogue.length,
        photos: catalogue,
      },
      null,
      2,
    )}\n`,
  );

  const byOrientation = catalogue.reduce((acc, p) => {
    acc[p.orientation] = (acc[p.orientation] ?? 0) + 1;
    return acc;
  }, {});

  console.log("");
  console.log(
    `${built} photographs → ${(bytes / 1048576).toFixed(1)}MB of WebP`,
  );
  console.log(
    `orientation: ${Object.entries(byOrientation)
      .map(([k, v]) => `${v} ${k}`)
      .join(", ")}`,
  );
  console.log(`catalogue: ${path.relative(ROOT, CATALOGUE)}\n`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
