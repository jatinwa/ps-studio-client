import raw from "./catalogue.json";

/* ───────────────────────────────────────────────────────────
   The studio's real photographs.

   catalogue.json is generated by `npm run photos` from whatever
   is in incoming/, so this layer never hard-codes a filename.
   ─────────────────────────────────────────────────────────── */

export interface Photo {
  id: string;
  file: string;
  width: number;
  height: number;
  ratio: number;
  orientation: "portrait" | "landscape" | "square";
  widths: number[];
}

export const photos: Photo[] = (raw.photos as Photo[]).slice();

export const byId = new Map(photos.map((p) => [p.id, p]));

export const landscape = photos.filter((p) => p.orientation === "landscape");
export const portrait = photos.filter((p) => p.orientation === "portrait");

export function photo(id: string): Photo {
  const found = byId.get(id);
  if (!found) throw new Error(`[photos] unknown photograph "${id}"`);
  return found;
}

/** Deterministic pick, so the layout is stable between builds. */
export function pick(list: Photo[], n: number, offset = 0): Photo[] {
  const out: Photo[] = [];
  for (let i = 0; i < n && i < list.length; i += 1) {
    out.push(list[(offset + i) % list.length]);
  }
  return out;
}

export function src(p: Photo, width: number): string {
  const best =
    p.widths.find((w) => w >= width) ?? p.widths[p.widths.length - 1] ?? 800;
  return `/media/photos/${p.id}-${best}.webp`;
}

export function srcSet(p: Photo): string {
  return p.widths.map((w) => `/media/photos/${p.id}-${w}.webp ${w}w`).join(", ");
}

export function thumb(p: Photo): string {
  return `/media/photos/${p.id}-thumb.webp`;
}

/**
 * Alt text.
 *
 * These are real client photographs and nobody has described them, so the alt
 * stays honest and generic rather than inventing what is in the frame. Replace
 * per-photo captions in the catalogue when the studio supplies them.
 */
export function alt(p: Photo, context = "Photograph by Payal Studios"): string {
  return context;
}
